// Utility functions for better image optimization
export const getOptimizedImageSrc = (
  originalSrc: string,
  width?: number,
  height?: number
): string => {
  // Add query parameters for image optimization if your CDN supports it
  const url = new URL(originalSrc);
  if (width) url.searchParams.set('w', width.toString());
  if (height) url.searchParams.set('h', height.toString());
  url.searchParams.set('q', '80'); // Quality setting
  return url.toString();
};

export const getImageSrcSet = (originalSrc: string): string => {
  const baseSrc = originalSrc.split('?')[0];
  return [
    `${getOptimizedImageSrc(baseSrc, 400)} 400w`,
    `${getOptimizedImageSrc(baseSrc, 600)} 600w`,
    `${getOptimizedImageSrc(baseSrc, 800)} 800w`,
    `${getOptimizedImageSrc(baseSrc, 1200)} 1200w`,
  ].join(', ');
};

// Helper function to create optimized image attributes
export const createImageProps = (
  project: Project,
  width?: number,
  height?: number
): {
  src: string;
  srcSet: string;
  alt: string;
  loading: 'lazy' | 'eager';
  decoding: 'async';
  sizes: string;
} => ({
  src: getOptimizedImageSrc(project.image, width, height),
  srcSet: getImageSrcSet(project.image),
  alt: project.title,
  loading: 'lazy',
  decoding: 'async',
  sizes: '(max-width: 768px) 100vw, (max-width: 1200px) 50vw, 33vw',
});

